#ifndef __RC522_TASK_
#define __RC522_TASK_

#include "stm32f4xx.h"

// ══════════════════════════════════════════════════════════════════════════
//  刷卡开锁 —— RC522(MF522)业务层
//
//  三层分工(和指纹那条链完全对应):
//      硬件层  spi.c 的 spi3_Config() / SPI3_Echo()   PC10/PC11/PC12(AF6)
//      协议层  rfid.c / rfid.h                        官方移植的寻卡/防冲突/读写块
//      业务层  本文件                                 寻到卡 → 比对卡号 → 开锁
//                                                     (相当于 finger.c 在 MG200 那边的角色)
//
//  "谁有资格开锁"这件事的答案存在 AT24C04A EEPROM 里(掉电不丢),
//  布局见 rc522_task.c 顶部。**第一张刷上去的卡会自动被录成授权卡**,
//  之后只认它 —— 和 lock 的密码"首次上电写入默认值"是同一套做法。
// ══════════════════════════════════════════════════════════════════════════

/**
 * 🟡 L1 架构代码 —— 生命周期约束:内含 RC522 硬复位和一次 EEPROM 读(都是裸机忙等),必须赶在调度器启动前调用
 * @brief  刷卡模块初始化:配好 RC522,再从 EEPROM 载入已授权的卡号
 * @return 无
 * @note   **必须在 vTaskStartScheduler() 之前调用**,理由和 lock_init() 一样:
 *         里面走的是 Delay_Us / I2C 那种忙等延时,调度器起来之后调会把别的
 *         任务饿死。
 * @note   依赖 i2c_bus_config(&i2c_bus_at24c04) 已经把 EEPROM 那条 I2C 总线配好。
 */
void rc522_init(void);

/**
 * 🟡 L1 架构代码 —— 创建时机的依赖写在接口上:要等 lock_tasks_init() 之后,否则刷卡通过了也没有任务去驱动电机
 * @brief  创建刷卡任务
 * @return 无
 * @note   刷卡走的是 lock.c 的公共开锁流程(lock_open / lock_is_busy),
 *         所以要在 lock_tasks_init() 之后调用。
 */
void rc522_tasks_init(void);

/**
 * 🟡 L1 架构代码 —— 跨任务投递意图的入口:置标志就返回,绝不在这里干活;"谁拥有外设谁干活"这条分工是它存在的理由
 * @brief  请求进入"加卡"模式,等一张卡放上来并把它录成授权卡(管理员模式 333# 派下来的活)
 * @return 无
 * @note   **只是投递意图,不是执行**。真正干活的是 rc522_task —— 只有它持有
 *         RC522(SPI3)。管理员模式不能自己去寻卡:一是它跑在 lock_task 里,
 *         等卡放上来会把锁的电机状态机拖停摆;二是两个任务同时做 SPI 事务
 *         必然串数据。
 * @note   录入期间**不会**做常规的"刷卡开锁"判断,而且旧卡号会被直接覆盖
 *         (一次只认一张卡,和首次自动录入是同一个存储位置)。
 * @note   可以在任何任务里调(内部只是置一个字节的标志)。
 */
void rc522_request_learn(void);

/**
 * 🔴 L0 生死线代码 —— 删掉授权卡号之后,下一张刷上来的卡会被**自动录成新的授权卡**;这个"没卡就等于谁都能登记"的性质是它区别于普通"删除"的地方
 * @brief  请求删除已授权的卡号(管理员模式 111# 派下来的活)
 * @return 无
 * @note   ⚠ 删完之后本模块退回"还没有授权卡"的状态,而那个状态下的行为是
 *         **第一张刷上来的卡自动被录成授权卡**(见 rc522_task.c 顶部)。
 *         也就是说 111# 之后如果有人趁主人没注意刷一张卡,锁就归他了。
 *         这是这门锁原本就有的设计(首次使用免配置),不是本次改动引入的,
 *         但 111# 让这个状态可以被主动触发,所以特别标出来。
 */
void rc522_request_erase(void);

#endif
