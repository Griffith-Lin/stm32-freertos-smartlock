#ifndef __LOCK_
#define __LOCK_

#include "stm32f4xx.h"
#include "FreeRTOS.h"
#include "task.h"
#include "queue.h"

// 密码锁业务逻辑
//   输入设备:电容触摸板(CY9CMBR3116),按键经 cy9cm_key_queue 送到这里
//   密码存储:AT24C04A EEPROM(掉电不丢),首次上电自动写入默认密码
//   输出:      LCD 显示输入界面;密码正确后驱动 L9110S 电机动作出锁
//
// 按键约定(4x3 键盘):
//   '0'~'9'  输入密码,屏幕上一个 '-'
//   '*'      清空已输入的,重新输
//   '#'      确认,校验密码

#define LOCK_PWD_LEN         6       // 密码位数
#define LOCK_OPEN_MS         3000    // 开锁后**保持**多久自动回锁(ms),不是电机行程时间

// ── 电机行程时间:开锁和回锁**各给一个**,不要合成一个 ──
//   为什么必须分开:推锁舌出去和收锁舌回来是两个不同的物理过程 ——
//   行程长度、弹簧压力、传动阻力都不一样。合成一个值喂给两边,必然
//   一边偏早(锁舌还没走到底电机就刹车了,锁没真正打开)、
//   一边偏晚(已经顶到头还在继续转,堵转发热,久了烧线圈)。
//
//   怎么调:先把两个值都放大到大得离谱(比如 2000),听电机声音 ——
//   "哒"一声到位、声音从轻快变沉,那一刻就是真实行程。记下时间再往回收
//   一点余量(机械会磨损、电池会掉压,别贴着临界值用)。
//   调完直接听:开锁和回锁听到的到位时刻不一样,就说明这两个宏确实该分开。
#define LOCK_MOTOR_OPEN_MS   500     // 开锁:推锁舌出去,电机正转多久(ms)
#define LOCK_MOTOR_CLOSE_MS  200     // 回锁:收锁舌回来,电机反转多久(ms)

// ── 锁控命令(远程来源:MQTT 云端下发)──
//
// 为什么不让 wifi_task 直接调 lock_open()? 两个理由:
//   1) **优先级**。wifi 任务优先级 1(最低),lock 是 2。让低优先级任务去驱动
//      电机、再保持 3 秒,这 4 秒里 MQTT 的上报和下发全被堵住,USART2 的
//      环形缓冲还可能溢出丢字节。
//   2) **单一决策者**。谁在开锁、LCD 该显示什么,只能有一个人说了算。
//      指纹、密码、云端三条路都去抢 LCD 和电机,迟早串。
//      所以统一成:任何人都只能"投递一个意图",由 lock_task 决定做不做。
//
// 平台约定(分包平台 attributes/push 话题):
//     {"DoorLock":1}  → 开锁
//     {"DoorLock":0}  → 关锁
typedef enum
{
    LOCK_CMD_OPEN = 0,      // 对应 {"DoorLock":1},见 lock_post_cmd() 的说明
    LOCK_CMD_CLOSE          // 对应 {"DoorLock":0}
} lock_cmd_t;

/**
 * 🟡 L1 架构代码 —— 模块对外的锁控入口,契约是"投递意图而非执行动作"且绝不阻塞:满了丢命令,才保证 wifi_task 不被拖慢
 * @brief  投递一条锁控命令(非阻塞)
 * @param  cmd 命令
 * @return 1 = 已入队;0 = 队列没建好 或 已满,被丢弃(已打印日志)
 * @note   **只能在任务里调**,不能在中断里调(内部用的是 xQueueSend,
 *         不是 FromISR 版本)。当前唯一的调用方是 wifi_task。
 *         故意不阻塞:命令的时效性很强,排不上队就该丢,而不是让调用者
 *         (比如 wifi 任务)卡在这里等 —— 它卡住会连累 MQTT 的心跳和接收。
 */
uint8_t lock_post_cmd(lock_cmd_t cmd);

/**
 * 🟡 L1 架构代码 —— 生命周期约束写在接口上:必须赶在调度器启动前调用(内含 EEPROM 忙等写),之后再调会饿死其他任务;载入后密码只在 RAM 里用
 * @brief  密码锁初始化:从 EEPROM 加载密码(没有就写默认值)+ 画开机界面
 * @return 无
 * @note   **必须在 vTaskStartScheduler() 之前调用**。
 *         里面会走一次 EEPROM 写(首次上电时),而 AT24C04_page_write() 用的是
 *         Delay_Ms() 忙等——裸机阶段无所谓,调度器起来之后会把别的任务饿死。
 *         加载完之后密码缓存在 RAM 里,任务阶段不再碰 EEPROM。
 */
void lock_init(void);

/**
 * 🟡 L1 架构代码 —— 创建时机的依赖写在接口上:要等 cy9cm_tasks_init() 建好 cy9cm_key_queue 之后再调,顺序反了任务就没有按键队列可收
 * @brief  创建密码处理任务
 * @return 无
 * @note   在 vTaskStartScheduler() 之前调用。任务阻塞在 cy9cm_key_queue 上,
 *         没按键时不占 CPU。依赖 cy9cm_tasks_init() 已经建好队列。
 */
void lock_tasks_init(void);

/**
 * 🟡 L1 架构代码 —— 本地开锁的唯一入口:返回值语义(1=受理/0=忙被拒)和非阻塞约定,要求密码、指纹、云端三条路共用这一份互斥判断
 * @brief  开锁 —— 本地开锁来源的公共出口(密码、指纹都走这里)
 * @param  title 开锁期间标题行显示的 ASCII 文字
 * @param  color 标题颜色
 * @return 1 = 已受理,锁会由 lock_task 驱动着打开;0 = 已有开锁流程在进行,本次被忽略
 * @note   **已经改成非阻塞了**(原来在这里一觉睡 4 秒)。现在只做三件事:
 *         抢占"正在开锁"标志、写 LCD 标题、把状态机推到"推锁舌"。
 *         之后的电机行程、3 秒保持、自动回锁,全部由 lock_task 每 20ms 的
 *         tick 推进(见 lock.c 的 lock_tick())。
 *
 *         为什么非拆不可:远程"关锁"要求**立刻回锁**,而如果这里阻塞 4 秒,
 *         关锁命令就只能在队列里干等 —— 那也是"关锁"这个动作名存实亡的原因。
 *         拆开之后保持期随时可被打断。
 * @note   **互斥仍然保留**:同一时刻只允许一个开锁流程,免得两个任务同时去推
 *         电机。"检查 + 占用标志"这两步放在临界区里做 —— 中间只要被 SysTick
 *         切走一次,两个任务就可能都读到"没人开锁",然后一起去驱动 L9110S。
 * @note   **不能在中断里调**:里面要写 LCD、还要进出临界区,都不是中断安全的。
 *         中断里想开锁就发个队列/信号量出来。
 */
uint8_t lock_open(uint8_t *title, uint16_t color);

/**
 * 🟢 L2 工具代码 —— 跨模块显示接口,契约只有一条:传入至少 8 个字符,否则字符格子盖不满会留下上一行标题的残影
 * @brief  只改标题行,不动锁(给指纹那种模块显示"没匹配上"之类的提示用)
 * @param  title ASCII 文字,**至少 8 个字符**
 * @param  color 颜色
 * @note   为什么要求 8 个字符:LCD_Font_Dis_Ascii() 会把每个字符格子的每个
 *         像素都写一遍(笔画写前景色、其余写背景色),所以只有"新文字不比旧
 *         文字短"才盖得干净。标题行原本是 "PASSWORD" 8 个字符,传个短的
 *         过去,右边会留下上一行标题的残影 —— 短了就用空格补齐。
 */
void lock_lcd_set_title(uint8_t *title, uint16_t color);

/**
 * 🟢 L2 工具代码 —— 只读的状态快照,给别的开锁来源做预检;返回 0 只代表"没在忙",最终是否受理仍要看 lock_open 的返回值
 * @brief  是否正在开锁/回锁
 * @return 1 = 正在进行
 * @note   给别的开锁来源做"预检",省得白采一次指纹再被 lock_open() 拒掉。
 *         真正的仲裁仍然是 lock_open() 自己,**不能只靠这个判断**。
 */
uint8_t lock_is_busy(void);

#endif
