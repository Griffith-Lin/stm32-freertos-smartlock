#ifndef __ADMIN_
#define __ADMIN_

#include "stm32f4xx.h"

// ══════════════════════════════════════════════════════════════════════════
//  管理员模式 —— 用密码开锁之后开一个 15 秒的窗口,在窗口里输入子模式代码
//
//      111#   初始化     清空指纹库 + 删除已授权的卡号
//      222#   改密码     连输两次新密码,两次一致才写入
//      333#   加卡       提示"放上卡",把读到的卡号写进 EEPROM
//      444#   加指纹     提示"放上手指",采满 3 次注册成新指纹
//      555#   蓝牙配网   手机连模块的 BLE 广播,把新的 WiFi 名/密码发过去,
//                        成功就存进 EEPROM 并改用新网,失败继续用当前网络
//
//  为什么入口是"密码开锁之后",而不是一个独立的按键:
//    管理员模式能删光指纹、改掉密码、换掉授权卡 —— 等于把整把锁的钥匙换一遍。
//    入口必须是一个只有主人知道的东西,密码正好就是。
//
//  ── 这个模块为什么是一台**不阻塞**的状态机 ──
//    它跑在 lock_task 里(经由 lock_handle_key)。而 lock_task 同时还负责每 20ms
//    推进一次锁的电机状态机(lock_tick):开锁 500ms → 保持 3 秒 → 回锁 200ms。
//    管理员模式一旦在里面阻塞(比如"等用户放上手指"等 20 秒),lock_tick()
//    就跟着停摆 —— 锁会一直开着不回锁,直到用户放完手指为止。
//    所以这里的每一段"等待"都必须拆成"状态 + 计时",由 admin_tick() 每 20ms
//    推进一步,绝不在这里 vTaskDelay 死等。
//
//  ── 同样因为上面这条,这里的**画屏也必须是不阻塞的** ──
//    不阻塞的"等待"好理解,不阻塞的"画屏"容易被忽略:大提示区一行 20 个字符
//    是 240×24 = 5760 个像素,而底层 LCD_Set_Point() 是**一个像素开一次 ST7789
//    地址窗口**的写法(每次要发 0x2B/0x2A/0x2C 和 4 个坐标字节),一行就要
//    一两百毫秒,整屏 6 行一秒往上。这跟"阻塞等手指"是同一件事:lock_task
//    在画屏期间一样回不到 lock_tick()。
//
//    ⚠ 具体的坑(真实踩过,上板现象是"密码开锁后电机一直转,远远超过
//      LOCK_MOTOR_OPEN_MS"):密码校验通过那一刻的调用链是
//         lock_handle_key → lock_verify → lock_open(电机已经正转)
//                        → admin_begin()
//      原来 admin_begin() 是同步把整屏菜单画完才返回的,于是负责给电机刹车
//      的 lock_tick() 整整一秒没机会跑,锁舌顶到头还在转。
//
//    所以规矩是两条,缺一不可:
//      ① 按键处理(admin_begin / admin_handle_key / admin_submit)一个像素
//         都不许碰,只改状态 + 把 s_redraw 置起来;
//      ② admin_tick() 里补画之前先问 lock_motor_running(),电机通着电就继续
//         欠着 —— 保持期内电机是刹车的,那时候画随便画。
//    另外整屏重画是**一次只画一行**,让 lock_task 每两行之间都能回去收一次
//    按键和远程命令,不至于一秒不理人。
//
//  ── 真正的长活派给谁 ──
//    录指纹要等手指、录卡要等卡、配网要等用户掏手机,这些等待天生是秒级的,
//    塞进 lock_task 不现实。所以 111# / 333# / 444# / 555# 只是**派活**:
//    置一个请求标志就退出管理员模式,由本来就拥有那个外设的任务去干 ——
//    finger_task 有 MG200 和 DETECT 脚,rc522_task 有 RC522,
//    wifi_task 有 USART2 和那套 AT 状态机 —— 它们各自用 lock.h 的大提示区
//    显示进度。只有 222#(改密码)是纯键盘输入,admin 自己从头做到尾。
//    (这也是"单一所有者"原则:外设归谁,活就归谁,别的模块只投递意图。
//     和 lock.h 里 lock_cmd_t 让云端投递而不是直接驱动电机是同一个套路。)
//
//  ⚠ 那些"派活"标志是跨任务写的(admin 写、finger/rc522/wifi 读),
//    读写都要放临界区,见各自 .c 里的说明。
//
//  ⚠ 派活和退出的**次序**是"先 admin_exit() 再置请求标志",不能反:
//    admin_exit() 里要 lock_screen_give() 把屏还回去(那一步含一次约 50ms 的
//    擦屏),而被派活的任务下一步就是 lock_screen_take()。反过来的话,对方
//    有大概 50ms 的窗口正好看见屏还占着,于是它"活照干、屏不画" ——
//    用户按了 555# 却整个配网过程屏幕全黑,只能靠串口才知道在发生什么。
// ══════════════════════════════════════════════════════════════════════════

// ── 时间参数 ──

// 管理员窗口时长。
// ⚠ 15 秒不是"从进窗口起数满 15 秒就关门",而是**每次按键都把 15 秒重新计时**:
//   输入 "111#" 要按 4 下,固定窗口的话手一慢就输不完,体验很差。
//   改成"最后一次按键之后 15 秒内没有新按键就退出",既保住了 15 秒的说法,
//   又不会把人卡在半截。
//   想要严格的固定窗口,把 admin_handle_key() 里刷新 s_last_key 那一行删掉即可。
// (原来给的 4 秒太短了:菜单本身要等电机刹车之后才画得出来,用户还得先看清
//  屏幕上哪行是哪行、再按 4 下键。15 秒是"够看完菜单再从容输入"的量。)
#define ADMIN_WINDOW_MS      15000

// 进了子模式(比如正在输新密码)之后,多久没按键就放弃。
// 要显著长于窗口:连输两次 6 位密码中间要想一下,十几秒不一定够。
#define ADMIN_SUB_TIMEOUT_MS 20000

// 结果提示("CARD SAVED" / "MISMATCH")在屏幕上停留多久再收工
#define ADMIN_MSG_MS         1500

/**
 * 🟡 L1 架构代码 —— 它只被 lock_verify() 在**开锁成功之后**调一次,这个时机决定了"谁能进管理员模式";窗口没能独占屏幕时会主动放弃,不会和正在进行的录入流程抢屏
 * @brief  进入管理员模式:开始计时,菜单**欠着**等 admin_tick() 补画
 * @return 无
 * @note   密码校验通过、lock_open() 受理之后才会调到这里,所以调用时锁**正在开**、
 *         电机正在转,s_unlocking 是 1。这也是 lock_handle_key() 里管理员模式
 *         必须排在 s_unlocking 判断之前的原因(否则整个窗口的键全被吞掉)。
 * @note   ⚠ **这里一个像素都不许画**。调用它的那一刻电机刚正转起来,而
 *         lock_tick() 要等 LOCK_MOTOR_OPEN_MS(500ms)才去刹车;整屏菜单
 *         画完要一秒上下,同步画的话刹车就被拖到一秒以后了。
 *         菜单由 admin_tick() 在 lock_motor_running() == 0 之后补,见文件头。
 * @note   屏幕正被别的流程占着(比如上一次 333# 加卡还在等卡放上来)时也**不会**
 *         在这里发现 —— 抢屏挪到了补画那一刻,抢不到就整个放弃并打印原因。
 */
void admin_begin(void);

/**
 * 🟢 L2 工具代码 —— 无副作用的快照查询,唯一的作用是让 lock.c 决定"这个键该给谁"
 * @brief  管理员模式是否开着
 * @return 1 = 开着(期间所有按键都归管理员模式)
 */
uint8_t admin_is_active(void);

/**
 * 🟡 L1 架构代码 —— 按键分流的接管点:它一开着,lock.c 的密码输入逻辑就整个让位;必须能在 s_unlocking=1 时工作,否则这 4 秒形同虚设
 * @brief  把一个触摸板按键交给管理员模式
 * @param  key '0'~'9' / '*' / '#'
 * @note   只在 lock_task 里被调(经由 lock_handle_key),所以内部那些状态变量
 *         不需要临界区。
 * @note   管理员模式开着时**不会**再走到密码校验上去 —— 屏幕上显示的是菜单,
 *         再让 '#' 去验密码只会把界面搞乱。
 */
void admin_handle_key(uint8_t key);

/**
 * 🟡 L1 架构代码 —— 倒计时推进点:它必须由 lock_task 每 20ms 调一次,漏调的现象是"管理员模式进去就再也退不出来",而不是别的
 * @brief  推进管理员模式的倒计时 —— 由 lock_task 每 20ms 调一次
 * @return 无
 * @note   为什么要有这个函数:管理员模式的"多久没按键了"必须有人算,
 *         而它又不能自己阻塞等(见文件头)。挂在 lock_task 的节拍上最省事,
 *         和 lock_tick() 并排,一个推电机、一个推倒计时。
 * @note   它还负责**补画**欠着的画面(整屏重画一次只画一行,回显行单独一次),
 *         这是"按键处理不碰 LCD"那条规矩的另一半,见文件头。
 *         ⚠ 在 lock_task 里它必须排在 lock_tick() **后面** —— 画屏是慢的,
 *           排在刹车前面会把电机行程拖长。
 */
void admin_tick(void);

#endif
